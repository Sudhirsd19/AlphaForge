class _CandleAggregator:
    """
    Non-lookahead 1-minute closed candle aggregator.

    Aggregates ticks into 1-minute bars. A candle is closed ONLY after the
    minute interval has completed (i.e., a tick with a timestamp in the NEXT
    minute is received). No future tick is used for the current bar.
    """

    def __init__(self) -> None:
        self._current_minute: int | None = None
        self._open: float = 0.0
        self._high: float = 0.0
        self._low: float = 0.0
        self._close: float = 0.0
        self._volume: int = 0
        self._minute_start_ts: datetime | None = None
        self._tick_count: int = 0

    def add_tick(self, price: float, quantity: int, exchange_ts: datetime) -> dict[str, Any] | None:
        """
        Add a tick and return a closed candle dict if the previous minute completed.

        Returns None if no candle was closed yet.
        """
        tick_minute = exchange_ts.minute + exchange_ts.hour * 60

        if self._current_minute is None:
            # First tick
            self._start_new_bar(price, quantity, exchange_ts, tick_minute)
            return None

        if tick_minute != self._current_minute:
            # Minute boundary crossed — close the previous bar
            closed_candle = {
                "open": self._open,
                "high": self._high,
                "low": self._low,
                "close": self._close,
                "volume": self._volume,
                "minute_start_ts": self._minute_start_ts,
                "tick_count": self._tick_count,
            }
            # Start new bar with current tick
            self._start_new_bar(price, quantity, exchange_ts, tick_minute)
            return closed_candle

        # Same minute — update running bar
        self._high = max(self._high, price)
        self._low = min(self._low, price)
        self._close = price
        self._volume += quantity
        self._tick_count += 1
        return None

    def _start_new_bar(self, price: float, quantity: int, ts: datetime, minute_key: int) -> None:
        self._current_minute = minute_key
        self._open = price
        self._high = price
        self._low = price
        self._close = price
        self._volume = quantity
        self._minute_start_ts = ts.replace(second=0, microsecond=0)
        self._tick_count = 1


class UpstoxMarketDataAdapter(AbstractMarketDataStreamAdapter):
    """
    Read-only Upstox WebSocket v3 market data adapter for shadow validation.

    SAFETY: This class contains ZERO order-routing methods.
    It does NOT import, reference, or expose any order placement, modification,
    or cancellation API. It is strictly a market-data consumer.

    PROVENANCE: Every received payload generates an authentic FeedProvenanceToken
    with alpha_forge_attestation_hmac (INTERNAL AlphaForge attestation, NOT an
    Upstox signature). Raw wire bytes are captured and SHA-256 hashed.
    """

    def __init__(
        self,
        contract: ContractMaster,
        access_token: str | None = None,
        instrument_key: str | None = None,
        queue_size: int = 1000,
        overflow_policy: QueueOverflowPolicy = QueueOverflowPolicy.FAIL_CLOSED,
        reconnect_policy: ReconnectPolicy | None = None,
    ) -> None:
        super().__init__(contract=contract, provider_name=UPSTOX_PROVIDER_NAME)

        # --- Contract validation (fail-closed) ---
        self._validate_contract(contract)

        # --- Credentials (fail-closed if missing) ---
        self._access_token = access_token or os.environ.get(UPSTOX_ACCESS_TOKEN_ENV)
        self._instrument_key = instrument_key or os.environ.get(
            UPSTOX_INSTRUMENT_KEY_ENV,
            f"NSE_FO|{contract.contract_id}",
        )

        # --- Connection and streaming state ---
        self._websocket_uri: str | None = None
        self._provider_authenticated: bool = False
        self._ws: Any = None  # websockets.WebSocketClientProtocol at runtime
        self._queue_size = queue_size
        self._overflow_policy = overflow_policy
        self._reconnect_policy = reconnect_policy or ReconnectPolicy(
            max_attempts=MAX_RECONNECT_ATTEMPTS,
            base_delay_seconds=RECONNECT_BASE_DELAY_SECONDS,
            max_delay_seconds=RECONNECT_MAX_DELAY_SECONDS,
        )
        self._reconnect_fsm = ReconnectStateMachine(policy=self._reconnect_policy)
        self._ingestion_sequence_no: int = 0

        # --- Telemetry ---
        self._connection_start_ts: datetime | None = None
        self._connection_established_ts: datetime | None = None
        self._subscription_start_ts: datetime | None = None
        self._first_event_ts: datetime | None = None
        self._disconnect_ts: datetime | None = None
