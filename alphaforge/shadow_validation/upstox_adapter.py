    def disconnect(self) -> None:
        """Safely terminate WebSocket connection."""
        self._is_connected = False
        self._disconnect_ts = datetime.now(UTC)
        self._disconnect_count += 1
        self._ws = None
        if hasattr(self, "_stream_stop_event") and self._stream_stop_event is not None:
            self._stream_stop_event.set()
        logger.info(
            f"UpstoxMarketDataAdapter: Disconnected. Session: {self._session_id}. "
            f"Total market events: {self._total_valid_market_events}."
        )

    def _create_provenance_token(
        self,
        raw_payload: bytes,
        source_ts: datetime,
        provider_event_id: str | None = None,
    ) -> FeedProvenanceToken:
        """
        Create an authentic FeedProvenanceToken for a received Upstox payload.

        PROVENANCE DISTINCTION:
        - raw_payload_hash: SHA-256 of the exact received wire bytes from Upstox.
        - alpha_forge_attestation_hmac: INTERNAL AlphaForge HMAC-SHA256 attestation
          proving this event was captured through the verified adapter ingestion path.
          This is NOT an Upstox signature and NOT a provider-origin signature.
        - provider_event_id: Upstox does not supply per-message sequence IDs in the
          protobuf payload, so this is set to None unless explicitly available.
        """
        if not self._is_connected:
            msg = "UpstoxMarketDataAdapter: Cannot create provenance token while disconnected."
            raise DataIntegrityError(msg)

        raw_hash = hashlib.sha256(raw_payload).hexdigest()
        attestation_hmac = ProvenanceVerifier.generate_attestation_hmac(
            provider=UPSTOX_PROVIDER_NAME,
            session_id=self._session_id,
            raw_payload_hash=raw_hash,
        )

        return FeedProvenanceToken(
            provider=UPSTOX_PROVIDER_NAME,
            provider_authenticated=self._provider_authenticated,
            connection_session_id=self._session_id,
            source_timestamp=source_ts,
            provider_event_id=provider_event_id,
            raw_payload_hash=raw_hash,
            alpha_forge_attestation_hmac=attestation_hmac,
            is_live_external=True,
        )

    def _decode_protobuf_message(self, raw_bytes: bytes) -> dict[str, Any] | None:
        """
        Decode Upstox v3 protobuf binary message into a dict.

        Returns None if the message cannot be decoded (malformed payload).
        """
        try:
            from google.protobuf.json_format import MessageToDict  # noqa: PLC0415

            from alphaforge.shadow_validation import (  # noqa: PLC0415
                upstox_protobuf_pb2 as pb,
            )

            feed_response = pb.FeedResponse()  # type: ignore[attr-defined]
            feed_response.ParseFromString(raw_bytes)
            return MessageToDict(feed_response)
        except Exception:
            logger.warning(
                "UpstoxMarketDataAdapter: Failed to decode protobuf message. Flagging as INVALID.",
                exc_info=True,
            )
            self._invalid_events += 1
            return None

    def _extract_market_events_from_feed(
        self,
        decoded: dict[str, Any],
        raw_bytes: bytes,
        receive_ts: datetime,
    ) -> list[MarketStreamEvent]:
        """
        Extract normalized MarketStreamEvent(s) from a decoded FeedResponse.

        Handles both:
        - MarketOHLC bars (1-minute closed candles from provider)
        - LTPC ticks (aggregated into 1-minute bars by _CandleAggregator)

        Never fabricates timestamps, event IDs, or sequence numbers.
        """
        events: list[MarketStreamEvent] = []
        feeds = decoded.get("feeds", {})

        for instrument_key, feed_data in feeds.items():
            # Skip instruments that don't match our subscription
            if not self._is_target_instrument(instrument_key):
                continue

            full_feed = feed_data.get("fullFeed", {})
            market_ff = full_feed.get("marketFF", {})
            index_ff = full_feed.get("indexFF", {})
            ltpc_data = feed_data.get("ltpc") or market_ff.get("ltpc") or index_ff.get("ltpc")
            ohlc_list = market_ff.get("marketOHLC", {}).get("ohlc", []) or index_ff.get(
                "marketOHLC", {}
            ).get("ohlc", [])

            # --- Process OHLC bars (provider-supplied 1-minute candles) ---
            processed_1m_candle = False
            for ohlc in ohlc_list:
                interval = ohlc.get("interval", "")
                if interval != "1m":
                    continue  # Only process 1-minute bars

                try:
                    ts_ms = int(ohlc.get("ts", 0))
                    o_price = float(ohlc.get("open", 0.0))
                    h_price = float(ohlc.get("high", 0.0))
                    l_price = float(ohlc.get("low", 0.0))
                    c_price = float(ohlc.get("close", 0.0))
                    vol = int(float(ohlc.get("vol", 0)))
                except (ValueError, TypeError):
                    self._invalid_events += 1
                    continue

                if ts_ms <= 0:
                    self._invalid_events += 1
                    continue

                exchange_ts = datetime.fromtimestamp(ts_ms / 1000.0, tz=UTC)
                provenance = self._create_provenance_token(
                    raw_payload=raw_bytes,
                    source_ts=exchange_ts,
                    provider_event_id=None,  # Upstox does not supply per-OHLC event IDs
                )

                self._last_sequence_no += 1
                event = self._build_market_stream_event(
                    exchange_ts=exchange_ts,
                    receive_ts=receive_ts,
                    open_price=o_price,
                    high_price=h_price,
                    low_price=l_price,
                    close_price=c_price,
                    volume=vol,
                    provenance=provenance,
                )
                if event:
                    events.append(event)
                    processed_1m_candle = True

            # --- Process LTPC ticks (aggregate into 1-minute closed candles) ---
            # If no provider-supplied 1m bar arrived, aggregate incoming ticks via _CandleAggregator
            if ltpc_data and not processed_1m_candle:
                try:
                    ltp = float(ltpc_data.get("ltp", 0.0))
                    ltt_ms = int(ltpc_data.get("ltt", 0))
                    ltq = int(float(ltpc_data.get("ltq", 0)))
                except (ValueError, TypeError):
                    self._invalid_events += 1
                    continue

                if ltp <= 0 or ltt_ms <= 0:
                    self._invalid_events += 1
                    continue

                exchange_ts = datetime.fromtimestamp(ltt_ms / 1000.0, tz=UTC)
                closed_candle = self._candle_aggregator.add_tick(ltp, ltq, exchange_ts)

                if closed_candle:
                    candle_ts = closed_candle["minute_start_ts"]
                    provenance = self._create_provenance_token(
                        raw_payload=raw_bytes,
                        source_ts=candle_ts,
                        provider_event_id=None,
                    )
                    self._last_sequence_no += 1
                    event = self._build_market_stream_event(
                        exchange_ts=candle_ts,
                        receive_ts=receive_ts,
                        open_price=closed_candle["open"],
                        high_price=closed_candle["high"],
                        low_price=closed_candle["low"],
                        close_price=closed_candle["close"],
                        volume=closed_candle["volume"],
                        provenance=provenance,
                    )
                    if event:
                        events.append(event)

        return events

    def _build_market_stream_event(
        self,
        exchange_ts: datetime,
        receive_ts: datetime,
        open_price: float,
        high_price: float,
        low_price: float,
        close_price: float,
        volume: int,
        provenance: FeedProvenanceToken,
    ) -> MarketStreamEvent | None:
        """Build a validated MarketStreamEvent with anomaly detection."""
        anomalies: list[MarketDataAnomalyType] = []

        # Validate prices
        if any(p <= 0 for p in (open_price, high_price, low_price, close_price)):
            anomalies.append(MarketDataAnomalyType.INVALID)
            self._invalid_events += 1
            return None

        # Session boundary check
        event_time = exchange_ts.time()
        is_session = NSE_SESSION_START_UTC <= event_time <= NSE_SESSION_END_UTC

        # Duplicate detection via event hash
        event_hash = hashlib.sha256(
            f"{exchange_ts.isoformat()}-{close_price}-{volume}".encode()
        ).hexdigest()[:16]
        if event_hash in self._seen_event_hashes:
            anomalies.append(MarketDataAnomalyType.DUPLICATE)
            self._duplicate_events += 1
        self._seen_event_hashes.add(event_hash)

        # Out-of-order check
        if self._last_event_ts and exchange_ts < self._last_event_ts:
            anomalies.append(MarketDataAnomalyType.OUT_OF_ORDER)
            self._out_of_order_events += 1

        self._last_event_ts = exchange_ts
        self._total_valid_market_events += 1

        if self._first_event_ts is None:
            self._first_event_ts = exchange_ts

        processing_ts = datetime.now(UTC)
        self._last_sequence_no += 1
        self._ingestion_sequence_no = self._last_sequence_no

        event = MarketStreamEvent(
            event_id=f"UPSTOX-{self._session_id}-{self._last_sequence_no}",
            symbol=self._contract.underlying_symbol,
            contract_id=self._contract.contract_id,
            sequence_no=self._last_sequence_no,
            ingestion_sequence_no=self._ingestion_sequence_no,
            provider=UPSTOX_PROVIDER_NAME,
            instrument_key=self._instrument_key,
            raw_payload_hash=provenance.raw_payload_hash,
            exchange_timestamp=exchange_ts,
            ingestion_timestamp=receive_ts,
            processing_timestamp=processing_ts,
            open_price=Decimal(str(round(open_price, 2))),
            high_price=Decimal(str(round(high_price, 2))),
            low_price=Decimal(str(round(low_price, 2))),
            close_price=Decimal(str(round(close_price, 2))),
            volume=volume,
            data_source=DataSourceType.REAL_MARKET_SHADOW,
            anomalies=anomalies,
            is_session_valid=is_session,
            provenance=provenance,
        )
        self._reconnect_fsm.on_event_received(event)
        return event

    @property
    def subscription_instrument_key(self) -> str:
        """Resolve numeric Upstox instrument key for wire WebSocket subscription."""
        clean = self._instrument_key.replace("NSE_FO|", "")
        if clean in UPSTOX_KNOWN_INSTRUMENT_KEYS:
            return UPSTOX_KNOWN_INSTRUMENT_KEYS[clean]
        if self._instrument_key in UPSTOX_KNOWN_INSTRUMENT_KEYS:
            return UPSTOX_KNOWN_INSTRUMENT_KEYS[self._instrument_key]
        return self._instrument_key

    def _is_target_instrument(self, instrument_key: str) -> bool:
        """Check if the instrument key matches our configured subscription."""
        sub_key = self.subscription_instrument_key
        return (
            instrument_key == self._instrument_key
            or instrument_key == sub_key
            or instrument_key.endswith(f"|{self._contract.contract_id}")
            or instrument_key.endswith(f":{self._contract.contract_id}")
            or sub_key.endswith(f"|{instrument_key}")
            or instrument_key.endswith(sub_key)
            or (
                self._contract.underlying_symbol in instrument_key
                and ("FO" in instrument_key or "FUT" in instrument_key)
            )
        )

    @property
    def reconnect_fsm(self) -> ReconnectStateMachine:
        """Expose the reconnect and gap recovery state machine."""
        return self._reconnect_fsm

    async def stream_live_events(self) -> AsyncIterator[MarketStreamEvent]:
        """
        True real-time asynchronous market data streaming pipeline.

        Yields verified MarketStreamEvent immediately upon extraction and validation.
        Does NOT accumulate events in memory.
        """
        if not self._is_connected:
            msg = "UpstoxMarketDataAdapter: Not connected. Call connect() first. Failing closed."
            raise UpstoxConnectionError(msg)

        import websockets  # noqa: PLC0415

        ssl_context = ssl.create_default_context()

        try:
            async with websockets.connect(
                self._websocket_uri,  # type: ignore[arg-type]
                ssl=ssl_context,
            ) as ws:
                self._ws = ws
                logger.info("UpstoxMarketDataAdapter: WebSocket stream active (live pipeline).")

                # Subscribe to instrument using numeric wire key if available
                sub_key = self.subscription_instrument_key
                await asyncio.sleep(1)
                sub_msg = json.dumps(
                    {
                        "guid": f"alphaforge-{uuid.uuid4().hex[:8]}",
                        "method": "sub",
                        "data": {
                            "mode": "full",
                            "instrumentKeys": [sub_key],
                        },
                    }
                ).encode("utf-8")
                await ws.send(sub_msg)
                self._subscription_start_ts = datetime.now(UTC)
                logger.info(f"UpstoxMarketDataAdapter: Subscribed to {sub_key} (canonical: {self._instrument_key}).")

                async for message in ws:
                    receive_ts = datetime.now(UTC)
                    self._total_received_messages += 1
                    self._reconnect_fsm.on_message_received()

                    if isinstance(message, str):
                        raw_bytes = message.encode("utf-8")
                    else:
                        raw_bytes = bytes(message)

                    decoded = self._decode_protobuf_message(raw_bytes)
                    if decoded is None:
                        continue

                    msg_type = decoded.get("type", "")
                    if msg_type == "market_info":
                        self._heartbeat_count += 1
                        self._reconnect_fsm.on_heartbeat()
                        continue

                    events = self._extract_market_events_from_feed(decoded, raw_bytes, receive_ts)
                    for ev in events:
                        yield ev

        except websockets.ConnectionClosed as exc:
            logger.warning("UpstoxMarketDataAdapter: WebSocket connection closed by server.")
            self._reconnect_fsm.on_disconnect(
                DisconnectReason.SOCKET_DISCONNECT, details={"error": str(exc)}
            )
        except Exception as exc:
            logger.exception("UpstoxMarketDataAdapter: WebSocket stream error.")
            self._reconnect_fsm.on_disconnect(
                DisconnectReason.UNEXPECTED_TERMINATION, details={"error": str(exc)}
            )
            raise

    def stream_events(self) -> Iterator[MarketStreamEvent]:
        """
        True real-time synchronous streaming pipeline with bounded queue.

        Consumes events from the async stream in real time and yields them immediately
        to downstream consumers without full-session memory accumulation.

        Maintains bounded queue with explicit overflow behavior (FAIL_CLOSED / BACKPRESSURE).
        Never silently discards market events.
        """
        if not self._is_connected:
            msg = "UpstoxMarketDataAdapter: Not connected. Call connect() first. Failing closed."
            raise UpstoxConnectionError(msg)

        event_queue: queue.Queue[MarketStreamEvent | Exception | None] = queue.Queue(
            maxsize=self._queue_size
        )
        stop_event = threading.Event()

        def _worker() -> None:
            loop = asyncio.new_event_loop()
            asyncio.set_event_loop(loop)

            async def _consume() -> None:
                stream = self.stream_live_events()
                try:
                    async for event in stream:
                        if stop_event.is_set() or not self._is_connected:
                            break

                        if self._overflow_policy == QueueOverflowPolicy.FAIL_CLOSED:
                            try:
                                event_queue.put_nowait(event)
                            except queue.Full:
                                msg = (
                                    f"QUEUE_OVERFLOW: Ingestion queue capacity of "
                                    f"{self._queue_size} exceeded. Failing closed."
                                )
                                event_queue.put(DataIntegrityError(msg))
                                break
                        else:
                            # BACKPRESSURE
                            try:
                                event_queue.put(event, timeout=5.0)
                            except queue.Full:
                                msg = (
                                    f"QUEUE_BACKPRESSURE_TIMEOUT: Downstream consumer "
                                    f"blocked for >5.0s. Queue capacity {self._queue_size}. "
                                    f"Failing closed."
                                )
                                event_queue.put(DataIntegrityError(msg))
                                break
                except asyncio.CancelledError:
                    pass
                except Exception as exc:
                    event_queue.put(exc)
                finally:
                    try:
                        aclose = getattr(stream, "aclose", None)
                        if callable(aclose):
                            await aclose()
                    except Exception:  # noqa: S110
                        pass
                    event_queue.put(None)  # Sentinel to terminate generator

            async def _monitor_stop(consume_task: asyncio.Task[None]) -> None:
                while not stop_event.is_set() and self._is_connected:
                    await asyncio.sleep(0.05)
                if not consume_task.done():
                    consume_task.cancel()

            async def _main() -> None:
                consume_task = loop.create_task(_consume())
                monitor_task = loop.create_task(_monitor_stop(consume_task))
                with contextlib.suppress(asyncio.CancelledError):
                    await consume_task
                if not monitor_task.done():
                    monitor_task.cancel()
                    with contextlib.suppress(asyncio.CancelledError):
                        await monitor_task

            try:
                loop.run_until_complete(_main())
            finally:
                loop.close()

        worker_thread = threading.Thread(
            target=_worker,
            name="UpstoxLiveStreamWorker",
            daemon=True,
        )
        worker_thread.start()

        self._stream_stop_event = stop_event
        try:
            while self._is_connected and not stop_event.is_set():
                try:
                    item = event_queue.get(timeout=0.25)
                except queue.Empty:
                    continue
                if item is None:
                    break
                if isinstance(item, Exception):
                    raise item
                yield item
        finally:
            stop_event.set()
            self._stream_stop_event = None
            self.disconnect()
            worker_thread.join(timeout=2.0)

