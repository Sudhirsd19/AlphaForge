"""
AlphaForge Fundamental Scoring & Ranking Engine.
Maintains curated institutional balance sheet and operating data for 59 NSE market leaders.
Calculates multi-factor composite scores (0-100), executes dynamic price and sector filtering,
and generates leaderboard cards and comprehensive company deep-dive metrics.
"""

from __future__ import annotations

from alphaforge.fundamentals.models import (
    FundamentalUniverseResponse,
    HealthRating,
    LeaderboardSummary,
    StockFundamental,
    VerdictType,
)


def calculate_fundamental_scores(
    roe: float,
    roce: float,
    debt_to_equity: float,
    pe_ratio: float,
    dividend_yield: float,
    profit_growth_3y: float,
    sales_growth_3y: float,
    sector: str = "",
) -> tuple[int, int, int, int, int, VerdictType, HealthRating]:
    """
    Computes deterministic institutional composite score (0-100) across 4 pillars:
    - Profitability & Capital Efficiency (Max 30 pts)
    - Solvency & Balance Sheet (Max 25 pts)
    - Valuation Attractiveness (Max 25 pts)
    - Growth Consistency (Max 20 pts)
    """
    # 1. Profitability & Returns (Max 30)
    p_score = 0
    if roe >= 25.0:
        p_score += 15
    elif roe >= 18.0:
        p_score += 12
    elif roe >= 14.0:
        p_score += 9
    elif roe >= 10.0:
        p_score += 6
    else:
        p_score += 3

    if roce >= 25.0:
        p_score += 15
    elif roce >= 18.0:
        p_score += 12
    elif roce >= 14.0:
        p_score += 9
    elif roce >= 10.0:
        p_score += 6
    else:
        p_score += 3

    # 2. Solvency & Balance Sheet (Max 25)
    s_score = 0
    is_financial = "bank" in sector.lower() or "financ" in sector.lower()
    if is_financial:
        # For banks/NBFCs, evaluate leverage prudently based on Capital Adequacy & NPA standards
        if debt_to_equity <= 1.0:
            s_score = 25
        elif debt_to_equity <= 2.0:
            s_score = 22
        elif debt_to_equity <= 4.0:
            s_score = 18
        else:
            s_score = 15
    else:
        if debt_to_equity == 0.0:
            s_score = 25
        elif debt_to_equity <= 0.15:
            s_score = 22
        elif debt_to_equity <= 0.40:
            s_score = 18
        elif debt_to_equity <= 0.80:
            s_score = 13
        elif debt_to_equity <= 1.20:
            s_score = 8
        else:
            s_score = 4

    # 3. Valuation Attractiveness (Max 25)
    v_score = 0
    if 0 < pe_ratio < 15.0:
        v_score += 15
    elif 0 < pe_ratio < 25.0:
        v_score += 12
    elif 0 < pe_ratio < 38.0:
        v_score += 9
    elif 0 < pe_ratio < 60.0:
        v_score += 6
    elif pe_ratio >= 60.0:
        v_score += 3
    else:
        # Negative / zero P/E represents loss-making operations
        v_score += 0


    if dividend_yield >= 3.0:
        v_score += 10
    elif dividend_yield >= 1.5:
        v_score += 7
    elif dividend_yield >= 0.8:
        v_score += 5
    else:
        v_score += 3

    # 4. Growth Consistency (Max 20)
    g_score = 0
    if profit_growth_3y >= 20.0:
        g_score += 10
    elif profit_growth_3y >= 12.0:
        g_score += 8
    elif profit_growth_3y >= 7.0:
        g_score += 6
    else:
        g_score += 3

    if sales_growth_3y >= 18.0:
        g_score += 10
    elif sales_growth_3y >= 12.0:
        g_score += 8
    elif sales_growth_3y >= 6.0:
        g_score += 6
    else:
        g_score += 3

    total_score = p_score + s_score + v_score + g_score
    total_score = max(0, min(100, total_score))

    # Determine Verdict & Health Rating
    if total_score >= 85:
        verdict = VerdictType.STRONG_BUY
        health = HealthRating.EXCELLENT
    elif total_score >= 75:
        verdict = VerdictType.BUY
        health = HealthRating.ROBUST
    elif total_score >= 65:
        verdict = VerdictType.ACCUMULATE
        health = HealthRating.ROBUST
    elif total_score >= 55:
        verdict = VerdictType.FAIR_VALUE
        health = HealthRating.MODERATE
    else:
        verdict = VerdictType.HOLD
        health = HealthRating.MODERATE

    return p_score, s_score, v_score, g_score, total_score, verdict, health


